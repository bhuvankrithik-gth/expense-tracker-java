-- =====================================================================
-- Expense Tracker — database schema (MySQL 8 / MariaDB 10.5+)
-- Run:  mysql -h $DB_HOST -P $DB_PORT -u $DB_USER -p $DB_NAME < schema.sql
-- Week 12 (JDBC): tables are created by schema.sql; all reads/writes go
-- through the DAO layer using PreparedStatement (never string-concatenated SQL).
-- =====================================================================

CREATE DATABASE IF NOT EXISTS expensetracker
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE expensetracker;

-- ---------------------------------------------------------------------
-- users: one row per account. Passwords are PBKDF2 hashes, never plaintext.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(190) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,          -- format: iterations:salt:hash (Base64)
    currency      CHAR(3)      NOT NULL DEFAULT 'INR',  -- display currency: INR/USD/EUR/JPY
    theme         VARCHAR(10)  NOT NULL DEFAULT 'light',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_email (email),            -- login lookup must be unique
    CONSTRAINT chk_users_currency CHECK (currency IN ('INR','USD','EUR','JPY'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- categories: default ones (Food, Travel, ...) plus user-defined customs.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id         BIGINT       NOT NULL AUTO_INCREMENT,
    user_id    BIGINT       NOT NULL,
    name       VARCHAR(60)  NOT NULL,
    kind       VARCHAR(10)  NOT NULL DEFAULT 'both',  -- 'expense' | 'income' | 'both'
    is_default TINYINT(1)   NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uq_categories_user_name (user_id, name),
    KEY idx_categories_user (user_id),
    CONSTRAINT fk_categories_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_categories_kind CHECK (kind IN ('expense','income','both'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- transactions: every income / expense entry.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transactions (
    id             BIGINT          NOT NULL AUTO_INCREMENT,
    user_id        BIGINT          NOT NULL,
    category_id    BIGINT          NULL,
    type           VARCHAR(10)     NOT NULL,              -- 'expense' | 'income'
    amount         DECIMAL(14,2)   NOT NULL,
    currency       CHAR(3)         NOT NULL DEFAULT 'INR',-- currency the amount was entered in
    txn_date       DATE            NOT NULL,
    note           VARCHAR(255)    NULL,
    payment_method VARCHAR(40)     NULL,                  -- Cash / Card / UPI / Bank / Other
    created_at     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_txn_user_date (user_id, txn_date),            -- dashboard + filters
    KEY idx_txn_user_cat  (user_id, category_id),
    CONSTRAINT fk_txn_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_txn_category FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE SET NULL,
    CONSTRAINT chk_txn_type   CHECK (type IN ('expense','income')),
    CONSTRAINT chk_txn_amount CHECK (amount > 0)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- budgets: monthly spending limit per category (month stored as 'YYYY-MM').
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS budgets (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    user_id     BIGINT        NOT NULL,
    category_id BIGINT        NOT NULL,
    month       CHAR(7)       NOT NULL,                   -- e.g. '2026-10'
    amount      DECIMAL(14,2) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_budgets_user_cat_month (user_id, category_id, month),
    KEY idx_budgets_user_month (user_id, month),
    CONSTRAINT fk_budgets_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_budgets_category FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE CASCADE,
    CONSTRAINT chk_budgets_amount CHECK (amount > 0),
    CONSTRAINT chk_budgets_month  CHECK (month REGEXP '^[0-9]{4}-[0-9]{2}$')
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- alerts: budget warnings generated by the background budget watcher.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS alerts (
    id         BIGINT       NOT NULL AUTO_INCREMENT,
    user_id    BIGINT       NOT NULL,
    message    VARCHAR(255) NOT NULL,
    is_read    TINYINT(1)   NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_alerts_user (user_id, is_read, created_at),
    CONSTRAINT fk_alerts_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- activity_log: audit trail written by the producer-consumer log service.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity_log (
    id         BIGINT       NOT NULL AUTO_INCREMENT,
    user_id    BIGINT       NULL,
    action     VARCHAR(80)  NOT NULL,       -- e.g. 'LOGIN', 'TXN_ADD', 'BUDGET_SET'
    detail     VARCHAR(255) NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_activity_user (user_id, created_at),
    CONSTRAINT fk_activity_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;

